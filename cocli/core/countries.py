def country_code_for(name: str) -> Optional[str]:
    """Alpha-2 code for an English country name or a bare alpha-2 token,
    else None. 'Denmark' -> 'DK'; 'DK' -> 'DK'; 'Denmark, Inc.' -> None."""
    token = name.strip().rstrip(".").lower()
    if not token or len(token) > 40:
        return None
    code = COUNTRY_NAME_TO_CODE.get(token)
    if code:
        return code
    # Bare ISO 3166-1 alpha-2 code (e.g. "DK"). Any single-token two-letter
    # piece; alpha-2 covers most such short suffixes so a longer token is
    # deliberately not accepted here.
    if len(token) == 2 and token.isalpha() and token.isascii():
        return token.upper()
    return None
